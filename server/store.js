// Persistent storage (server/db.js: SQLite for one process, Postgres for the cluster): accounts
// (with roles, bans and mutes), sessions, characters, the social graph (friends, ignores, guilds),
// mail, player reports and realm settings such as the world seed — and, for a realm split into
// layers (several realm processes running copies of the world), which layers are up, who is on
// which, and where a player should go next (their party's layer, say).
import { openDb } from './db.js';

const PRESENCE_STALE = 45_000;  // ms: a layer that stopped refreshing its players has crashed
const LAYER_STALE = 15_000;     // ms: …or the layer itself

const SQLITE_SCHEMA = `
  CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
  CREATE TABLE IF NOT EXISTS accounts (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL UNIQUE COLLATE NOCASE,
    hash TEXT NOT NULL,
    created INTEGER NOT NULL
  );
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    created INTEGER NOT NULL,
    seen INTEGER NOT NULL
  );
  CREATE TABLE IF NOT EXISTS characters (
    id INTEGER PRIMARY KEY,
    account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    name TEXT NOT NULL UNIQUE COLLATE NOCASE,
    level INTEGER NOT NULL DEFAULT 1,
    look TEXT NOT NULL,
    data TEXT,
    created INTEGER NOT NULL,
    updated INTEGER NOT NULL
  );
  CREATE INDEX IF NOT EXISTS characters_by_account ON characters(account_id);
  CREATE TABLE IF NOT EXISTS friends (
    character_id INTEGER NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    friend_id INTEGER NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    PRIMARY KEY (character_id, friend_id)
  );
  CREATE TABLE IF NOT EXISTS ignores (
    character_id INTEGER NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    ignored_id INTEGER NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    PRIMARY KEY (character_id, ignored_id)
  );
  CREATE TABLE IF NOT EXISTS guilds (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL UNIQUE COLLATE NOCASE,
    tag TEXT NOT NULL UNIQUE COLLATE NOCASE,
    motd TEXT NOT NULL DEFAULT '',
    created INTEGER NOT NULL
  );
  CREATE TABLE IF NOT EXISTS guild_members (
    guild_id INTEGER NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
    character_id INTEGER NOT NULL UNIQUE REFERENCES characters(id) ON DELETE CASCADE,
    rank INTEGER NOT NULL DEFAULT 0,
    joined INTEGER NOT NULL
  );
  CREATE TABLE IF NOT EXISTS mail (
    id INTEGER PRIMARY KEY,
    to_id INTEGER NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    from_name TEXT NOT NULL,
    body TEXT NOT NULL,
    gold INTEGER NOT NULL DEFAULT 0,
    item TEXT,
    sent INTEGER NOT NULL,
    read INTEGER NOT NULL DEFAULT 0,
    claimed INTEGER NOT NULL DEFAULT 0
  );
  CREATE INDEX IF NOT EXISTS mail_by_recipient ON mail(to_id);
  CREATE TABLE IF NOT EXISTS reports (
    id INTEGER PRIMARY KEY,
    reporter TEXT NOT NULL,
    target TEXT NOT NULL,
    reason TEXT NOT NULL,
    created INTEGER NOT NULL,
    handled INTEGER NOT NULL DEFAULT 0
  );
  CREATE TABLE IF NOT EXISTS layers (id INTEGER PRIMARY KEY, url TEXT NOT NULL, players INTEGER NOT NULL DEFAULT 0, draining INTEGER NOT NULL DEFAULT 0, seen INTEGER NOT NULL);
  CREATE TABLE IF NOT EXISTS presence (character_id INTEGER PRIMARY KEY, name TEXT NOT NULL, account_id INTEGER NOT NULL, layer INTEGER NOT NULL, seen INTEGER NOT NULL);
  CREATE INDEX IF NOT EXISTS presence_name ON presence(lower(name));
  CREATE TABLE IF NOT EXISTS affinity (character_id INTEGER PRIMARY KEY, layer INTEGER NOT NULL, intent TEXT, until INTEGER NOT NULL);
`;
// Columns added after the first release, so older SQLite databases get them too.
const LATER_COLUMNS = [
  ['accounts', 'role', "TEXT NOT NULL DEFAULT 'player'"],
  ['accounts', 'banned_until', 'INTEGER NOT NULL DEFAULT 0'],
  ['accounts', 'muted_until', 'INTEGER NOT NULL DEFAULT 0'],
];

// The same tables in Postgres (names unique regardless of case through lower() indexes).
const PG_SCHEMA = `
  CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
  CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    hash TEXT NOT NULL,
    created BIGINT NOT NULL,
    role TEXT NOT NULL DEFAULT 'player',
    banned_until BIGINT NOT NULL DEFAULT 0,
    muted_until BIGINT NOT NULL DEFAULT 0
  );
  CREATE UNIQUE INDEX IF NOT EXISTS accounts_name ON accounts (lower(name));
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    created BIGINT NOT NULL,
    seen BIGINT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS characters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    level INTEGER NOT NULL DEFAULT 1,
    look TEXT NOT NULL,
    data TEXT,
    created BIGINT NOT NULL,
    updated BIGINT NOT NULL
  );
  CREATE UNIQUE INDEX IF NOT EXISTS characters_name ON characters (lower(name));
  CREATE INDEX IF NOT EXISTS characters_by_account ON characters (account_id);
  CREATE TABLE IF NOT EXISTS friends (
    character_id BIGINT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    friend_id BIGINT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    PRIMARY KEY (character_id, friend_id)
  );
  CREATE INDEX IF NOT EXISTS friends_of ON friends (friend_id);
  CREATE TABLE IF NOT EXISTS ignores (
    character_id BIGINT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    ignored_id BIGINT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    PRIMARY KEY (character_id, ignored_id)
  );
  CREATE TABLE IF NOT EXISTS guilds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    tag TEXT NOT NULL,
    motd TEXT NOT NULL DEFAULT '',
    created BIGINT NOT NULL
  );
  CREATE UNIQUE INDEX IF NOT EXISTS guilds_name ON guilds (lower(name));
  CREATE UNIQUE INDEX IF NOT EXISTS guilds_tag ON guilds (lower(tag));
  CREATE TABLE IF NOT EXISTS guild_members (
    guild_id BIGINT NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
    character_id BIGINT NOT NULL UNIQUE REFERENCES characters(id) ON DELETE CASCADE,
    rank INTEGER NOT NULL DEFAULT 0,
    joined BIGINT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS guild_members_by_guild ON guild_members (guild_id);
  CREATE TABLE IF NOT EXISTS mail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    to_id BIGINT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    from_name TEXT NOT NULL,
    body TEXT NOT NULL,
    gold INTEGER NOT NULL DEFAULT 0,
    item TEXT,
    sent BIGINT NOT NULL,
    read INTEGER NOT NULL DEFAULT 0,
    claimed INTEGER NOT NULL DEFAULT 0
  );
  CREATE INDEX IF NOT EXISTS mail_by_recipient ON mail (to_id);
  CREATE TABLE IF NOT EXISTS reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter TEXT NOT NULL,
    target TEXT NOT NULL,
    reason TEXT NOT NULL,
    created BIGINT NOT NULL,
    handled INTEGER NOT NULL DEFAULT 0
  );
  CREATE TABLE IF NOT EXISTS layers (id INTEGER PRIMARY KEY, url TEXT NOT NULL, players INTEGER NOT NULL DEFAULT 0, draining INTEGER NOT NULL DEFAULT 0, seen BIGINT NOT NULL);
  CREATE TABLE IF NOT EXISTS presence (character_id BIGINT PRIMARY KEY, name TEXT NOT NULL, account_id BIGINT NOT NULL, layer INTEGER NOT NULL, seen BIGINT NOT NULL);
  CREATE INDEX IF NOT EXISTS presence_name ON presence (lower(name));
  CREATE INDEX IF NOT EXISTS presence_layer ON presence (layer);
  CREATE TABLE IF NOT EXISTS affinity (character_id BIGINT PRIMARY KEY, layer INTEGER NOT NULL, intent TEXT, until BIGINT NOT NULL);
`;

const json = (v) => (v ? JSON.parse(v) : null);
class NotHeld extends Error {}  // backs a transaction out (see Store.together)
class Rollback extends Error {}
const marks = (list) => list.map(() => '?').join(', ');

export class Store {
  // `url`: a Postgres connection string (DATABASE_URL); otherwise SQLite in `dir`.
  constructor({ url = null, dir = 'data' } = {}) {
    this.db = openDb({ url, dir });
    this.kind = this.db.kind;
  }

  async init() {
    const db = this.db;
    if (this.kind === 'sqlite') {
      await db.exec(SQLITE_SCHEMA);
      for (const [table, column, type] of LATER_COLUMNS) {
        const have = (await db.all(`PRAGMA table_info(${table})`)).some((c) => c.name === column);
        if (!have) await db.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${type}`);
      }
    } else {
      // Several processes may start at once: one creates the tables, the others wait for it.
      await db.tx(async (t) => {
        await t.run('SELECT pg_advisory_xact_lock(424242)');
        for (const stmt of PG_SCHEMA.split(';').map((s) => s.trim()).filter(Boolean)) await t.run(stmt);
      });
    }
    return this;
  }

  close() { return this.db.close(); }

  async meta(key) { return (await this.db.get('SELECT value FROM meta WHERE key = ?', [key]))?.value ?? null; }
  async setMeta(key, value) {
    await this.db.run('INSERT INTO meta (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value', [key, String(value)]);
  }

  // The realm's world seed: fixed when the database is created, the same for everyone forever after.
  async worldSeed() {
    const wanted = String(process.env.WORLD_SEED ? Number(process.env.WORLD_SEED) >>> 0 : (Math.random() * 0xffffffff) >>> 0);
    await this.db.run('INSERT INTO meta (key, value) VALUES (?, ?) ON CONFLICT (key) DO NOTHING', ['world_seed', wanted]);
    return Number(await this.meta('world_seed'));
  }

  // A snapshot of the whole database into `file` (SQLite only: Postgres has pg_dump).
  async backup(file) {
    if (this.kind !== 'sqlite') return false;
    await this.db.exec(`VACUUM INTO '${file.replace(/'/g, "''")}'`);
    return true;
  }

  // ---------------------------------------------------------------- accounts and sessions
  accountByName(name) { return this.db.get('SELECT id, name, hash, role, banned_until, muted_until FROM accounts WHERE lower(name) = lower(?)', [name]); }
  accountById(id) { return this.db.get('SELECT id, name, role, banned_until, muted_until FROM accounts WHERE id = ?', [id]); }
  async addAccount(name, hash) { return (await this.db.get('INSERT INTO accounts (name, hash, created) VALUES (?, ?, ?) RETURNING id', [name, hash, Date.now()])).id; }
  async setRole(name, role) { return (await this.db.run('UPDATE accounts SET role = ? WHERE lower(name) = lower(?)', [role, name])) > 0; }
  async setBan(accountId, until) { await this.db.run('UPDATE accounts SET banned_until = ? WHERE id = ?', [until, accountId]); }
  async setMute(accountId, until) { await this.db.run('UPDATE accounts SET muted_until = ? WHERE id = ?', [until, accountId]); }

  async addSession(tokenHash, accountId) { const now = Date.now(); await this.db.run('INSERT INTO sessions (token_hash, account_id, created, seen) VALUES (?, ?, ?, ?)', [tokenHash, accountId, now, now]); }
  session(tokenHash) { return this.db.get('SELECT account_id, seen FROM sessions WHERE token_hash = ?', [tokenHash]); }
  async touchSession(tokenHash) { await this.db.run('UPDATE sessions SET seen = ? WHERE token_hash = ?', [Date.now(), tokenHash]); }
  async dropSession(tokenHash) { await this.db.run('DELETE FROM sessions WHERE token_hash = ?', [tokenHash]); }
  async pruneSessions(maxAgeMs) { await this.db.run('DELETE FROM sessions WHERE seen < ?', [Date.now() - maxAgeMs]); }

  // ---------------------------------------------------------------- characters
  async characters(accountId) {
    const rows = await this.db.all('SELECT id, name, level, look, updated FROM characters WHERE account_id = ? ORDER BY updated DESC', [accountId]);
    return rows.map((c) => ({ id: c.id, name: c.name, level: c.level, look: JSON.parse(c.look), updated: c.updated }));
  }
  async character(id) {
    const c = await this.db.get('SELECT id, account_id, name, level, look, data FROM characters WHERE id = ?', [id]);
    return c ? { id: c.id, accountId: c.account_id, name: c.name, level: c.level, look: JSON.parse(c.look), data: json(c.data) } : null;
  }
  characterByName(name) { return this.db.get('SELECT id, name, account_id, level FROM characters WHERE lower(name) = lower(?)', [name]); }
  async characterCount(accountId) { return (await this.db.get('SELECT COUNT(*) AS n FROM characters WHERE account_id = ?', [accountId])).n; }
  async characterNameTaken(name) { return !!(await this.characterByName(name)); }
  async addCharacter(accountId, name, look) {
    const now = Date.now();
    return (await this.db.get('INSERT INTO characters (account_id, name, look, created, updated) VALUES (?, ?, ?, ?, ?) RETURNING id', [accountId, name, JSON.stringify(look), now, now])).id;
  }
  // A character is written only by the layer holding their presence: a layer that stalled and
  // lost them to another can't write its old copy over the new one. False if it didn't hold them.
  async saveCharacter(id, data, level, layer, db = this.db) {
    return (await db.run('UPDATE characters SET data = ?, level = ?, updated = ? WHERE id = ? AND EXISTS (SELECT 1 FROM presence WHERE character_id = ? AND layer = ?)',
      [JSON.stringify(data), level, Date.now(), id, id, layer])) > 0;
  }
  // Writes that hand things from one place to another land together or not at all (a layer can
  // die between any two writes). `rows`: [{ id, data, level }].
  saveCharacters(rows, layer) {
    return this.together(async (t) => {
      for (const r of rows) if (!await this.saveCharacter(r.id, r.data, r.level, layer, t)) throw new NotHeld();
      return true;
    });
  }
  // A letter, and its sender without what it carries.
  postMail(from, layer, toId, fromName, body, gold, item) {
    return this.together(async (t) => {
      if (!await this.saveCharacter(from.id, from.data, from.level, layer, t)) throw new NotHeld();
      await this.sendMail(toId, fromName, body, gold, item, t);
      return true;
    });
  }
  // A letter claimed, and its claimer with what it carried: `take()` gives it to them (on the
  // server's copy) and returns their row, or null if it can't (then nothing is written: null).
  claimMailInto(id, toId, layer, take) {
    return this.together(async (t) => {
      if (!await this.claimMail(id, toId, t)) return null;
      const row = take();
      if (!row) throw new Rollback();
      if (!await this.saveCharacter(row.id, row.data, row.level, layer, t)) throw new NotHeld();
      return true;
    });
  }
  // A transaction that may back out: false if another layer holds a character in it (NotHeld),
  // null if there was nothing to do (Rollback).
  async together(fn) {
    try {
      return await this.db.tx(fn);
    } catch (err) {
      if (err instanceof NotHeld) return false;
      if (err instanceof Rollback) return null;
      throw err;
    }
  }
  async deleteCharacter(id, accountId) { return (await this.db.run('DELETE FROM characters WHERE id = ? AND account_id = ?', [id, accountId])) > 0; }

  // ---------------------------------------------------------------- social graph
  friends(charId) { return this.db.all('SELECT c.id, c.name, c.level FROM friends f JOIN characters c ON c.id = f.friend_id WHERE f.character_id = ? ORDER BY c.name', [charId]); }
  async friendOf(charId) { return (await this.db.all('SELECT character_id AS id FROM friends WHERE friend_id = ?', [charId])).map((r) => r.id); }
  async addFriend(charId, friendId) { await this.db.run('INSERT INTO friends (character_id, friend_id) VALUES (?, ?) ON CONFLICT DO NOTHING', [charId, friendId]); }
  async removeFriend(charId, friendId) { await this.db.run('DELETE FROM friends WHERE character_id = ? AND friend_id = ?', [charId, friendId]); }
  ignores(charId) { return this.db.all('SELECT c.id, c.name FROM ignores i JOIN characters c ON c.id = i.ignored_id WHERE i.character_id = ? ORDER BY c.name', [charId]); }
  async addIgnore(charId, otherId) { await this.db.run('INSERT INTO ignores (character_id, ignored_id) VALUES (?, ?) ON CONFLICT DO NOTHING', [charId, otherId]); }
  async removeIgnore(charId, otherId) { await this.db.run('DELETE FROM ignores WHERE character_id = ? AND ignored_id = ?', [charId, otherId]); }

  // Guilds (rank: 0 member, 1 officer, 2 leader).
  guildOf(charId) { return this.db.get('SELECT g.id, g.name, g.tag, g.motd, m.rank FROM guild_members m JOIN guilds g ON g.id = m.guild_id WHERE m.character_id = ?', [charId]); }
  guildMembers(guildId) { return this.db.all('SELECT c.id, c.name, c.level, m.rank FROM guild_members m JOIN characters c ON c.id = m.character_id WHERE m.guild_id = ? ORDER BY m.rank DESC, c.name', [guildId]); }
  async guildTaken(name, tag) { return !!(await this.db.get('SELECT id FROM guilds WHERE lower(name) = lower(?) OR lower(tag) = lower(?)', [name, tag])); }
  createGuild(name, tag, leaderId) {
    return this.db.tx(async (t) => {
      const { id } = await t.get('INSERT INTO guilds (name, tag, created) VALUES (?, ?, ?) RETURNING id', [name, tag, Date.now()]);
      await t.run('INSERT INTO guild_members (guild_id, character_id, rank, joined) VALUES (?, ?, ?, ?)', [id, leaderId, 2, Date.now()]);
      return id;
    });
  }
  async addMember(guildId, charId) { await this.db.run('INSERT INTO guild_members (guild_id, character_id, rank, joined) VALUES (?, ?, ?, ?)', [guildId, charId, 0, Date.now()]); }
  async removeMember(charId) { await this.db.run('DELETE FROM guild_members WHERE character_id = ?', [charId]); }
  async setRank(charId, rank) { await this.db.run('UPDATE guild_members SET rank = ? WHERE character_id = ?', [rank, charId]); }
  async setMotd(guildId, motd) { await this.db.run('UPDATE guilds SET motd = ? WHERE id = ?', [motd, guildId]); }
  async memberCount(guildId) { return (await this.db.get('SELECT COUNT(*) AS n FROM guild_members WHERE guild_id = ?', [guildId])).n; }
  async deleteGuild(guildId) { await this.db.run('DELETE FROM guilds WHERE id = ?', [guildId]); }

  // ---------------------------------------------------------------- mail
  async inbox(charId) {
    const rows = await this.db.all('SELECT id, from_name, body, gold, item, sent, read, claimed FROM mail WHERE to_id = ? ORDER BY sent DESC LIMIT 50', [charId]);
    return rows.map((m) => ({ ...m, item: json(m.item) }));
  }
  async unread(charId) { return (await this.db.get('SELECT COUNT(*) AS n FROM mail WHERE to_id = ? AND read = 0', [charId])).n; }
  async mailCount(charId) { return (await this.db.get('SELECT COUNT(*) AS n FROM mail WHERE to_id = ?', [charId])).n; }
  async sendMail(toId, fromName, body, gold, item, db = this.db) {
    await db.run('INSERT INTO mail (to_id, from_name, body, gold, item, sent) VALUES (?, ?, ?, ?, ?, ?)', [toId, fromName, body, gold, item ? JSON.stringify(item) : null, Date.now()]);
  }
  async mailOne(id, toId) {
    const m = await this.db.get('SELECT id, gold, item, claimed FROM mail WHERE id = ? AND to_id = ?', [id, toId]);
    return m ? { ...m, item: json(m.item) } : null;
  }
  async readMail(id, toId) { await this.db.run('UPDATE mail SET read = 1 WHERE id = ? AND to_id = ?', [id, toId]); }
  async claimMail(id, toId, db = this.db) { return (await db.run('UPDATE mail SET claimed = 1, read = 1 WHERE id = ? AND to_id = ? AND claimed = 0', [id, toId])) > 0; }
  async deleteMail(id, toId) { await this.db.run('DELETE FROM mail WHERE id = ? AND to_id = ?', [id, toId]); }

  // ---------------------------------------------------------------- reports
  async addReport(reporter, target, reason) { await this.db.run('INSERT INTO reports (reporter, target, reason, created) VALUES (?, ?, ?, ?)', [reporter, target, reason, Date.now()]); }
  reports() { return this.db.all('SELECT id, reporter, target, reason, created FROM reports WHERE handled = 0 ORDER BY created DESC LIMIT 20'); }
  async handleReport(id) { await this.db.run('UPDATE reports SET handled = 1 WHERE id = ?', [id]); }

  // ---------------------------------------------------------------- layers
  // A realm process says it's up (every few seconds), with how full it is.
  async announceLayer(id, url, players, draining = false) {
    await this.db.run('INSERT INTO layers (id, url, players, draining, seen) VALUES (?, ?, ?, ?, ?) ON CONFLICT (id) DO UPDATE SET url = excluded.url, players = excluded.players, draining = excluded.draining, seen = excluded.seen',
      [id, url, players, draining ? 1 : 0, Date.now()]);
  }
  async dropLayer(id) { await this.db.run('DELETE FROM layers WHERE id = ?', [id]); }
  liveLayers() { return this.db.all('SELECT id, url, players, draining FROM layers WHERE seen > ? ORDER BY id', [Date.now() - LAYER_STALE]); }

  // Presence: one row per character in the world, owned by the layer it's on. Taking it is the
  // lock that keeps a character on one layer at a time: it can be taken from a layer that has
  // stopped refreshing it (crashed) but otherwise waits until the old layer lets go (after saving).
  async claim(charId, name, accountId, layer) {
    const now = Date.now();
    return (await this.db.run(`INSERT INTO presence (character_id, name, account_id, layer, seen) VALUES (?, ?, ?, ?, ?)
      ON CONFLICT (character_id) DO UPDATE SET name = excluded.name, account_id = excluded.account_id, layer = excluded.layer, seen = excluded.seen
      WHERE presence.layer = excluded.layer OR presence.seen < ? OR presence.layer NOT IN (SELECT id FROM layers WHERE seen > ?)`,
    [charId, name, accountId, layer, now, now - PRESENCE_STALE, now - LAYER_STALE])) > 0;
  }
  async release(charId, layer) { await this.db.run('DELETE FROM presence WHERE character_id = ? AND layer = ?', [charId, layer]); }
  async clearLayer(layer) { await this.db.run('DELETE FROM presence WHERE layer = ?', [layer]); }
  async refreshLayer(layer) { await this.db.run('UPDATE presence SET seen = ? WHERE layer = ?', [Date.now(), layer]); }
  present(charId) { return this.db.get('SELECT character_id AS id, name, layer FROM presence WHERE character_id = ? AND seen > ?', [charId, Date.now() - PRESENCE_STALE]); }
  presentByName(name) { return this.db.get('SELECT character_id AS id, name, layer FROM presence WHERE lower(name) = lower(?) AND seen > ?', [name, Date.now() - PRESENCE_STALE]); }
  async presentIds(ids) {
    if (!ids.length) return new Set();
    const rows = await this.db.all(`SELECT character_id AS id FROM presence WHERE seen > ? AND character_id IN (${marks(ids)})`, [Date.now() - PRESENCE_STALE, ...ids]);
    return new Set(rows.map((r) => r.id));
  }
  async onlineCount() { return (await this.db.get('SELECT COUNT(*) AS n FROM presence WHERE seen > ?', [Date.now() - PRESENCE_STALE])).n; }
  onlineList(limit = 60) { return this.db.all('SELECT name, layer FROM presence WHERE seen > ? ORDER BY name LIMIT ?', [Date.now() - PRESENCE_STALE, limit]); }

  // Affinity: where a character should be put when they next join — their party's layer, or a
  // layer they're being moved to (with what to do on arrival: `intent`).
  async setAffinity(charId, layer, intent, ttlMs) {
    await this.db.run('INSERT INTO affinity (character_id, layer, intent, until) VALUES (?, ?, ?, ?) ON CONFLICT (character_id) DO UPDATE SET layer = excluded.layer, intent = excluded.intent, until = excluded.until',
      [charId, layer, intent ? JSON.stringify(intent) : null, Date.now() + ttlMs]);
  }
  // A party's hold on its members (see server/parties.js): like setAffinity, but it never
  // replaces a move that's under way (one with an intent).
  async pinAffinity(charId, layer, ttlMs) {
    const now = Date.now();
    await this.db.run('INSERT INTO affinity (character_id, layer, intent, until) VALUES (?, ?, NULL, ?) ON CONFLICT (character_id) DO UPDATE SET layer = excluded.layer, until = excluded.until WHERE affinity.intent IS NULL OR affinity.until < ?',
      [charId, layer, now + ttlMs, now]);
  }
  async affinity(charId) {
    const a = await this.db.get('SELECT layer, intent FROM affinity WHERE character_id = ? AND until > ?', [charId, Date.now()]);
    return a ? { layer: a.layer, intent: json(a.intent) } : null;
  }
  // What to do on arriving (once).
  async takeIntent(charId) {
    const a = await this.affinity(charId);
    if (a?.intent) await this.db.run('UPDATE affinity SET intent = NULL WHERE character_id = ?', [charId]);
    return a?.intent ?? null;
  }
  // A party letting a member go (a move under way stays).
  async dropAffinity(charId) { await this.db.run('DELETE FROM affinity WHERE character_id = ? AND intent IS NULL', [charId]); }
  async pruneAffinity() { await this.db.run('DELETE FROM affinity WHERE until < ?', [Date.now()]); }
}
